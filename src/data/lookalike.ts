// かたちが にている もじ（ならべよう レベル3 の ダミーに使う）
const GROUPS = [
  // ひらがな
  'ぬめ', 'ねれわ', 'はほけ', 'さちき', 'るろ', 'いこり', 'うつ', 'あおめ', 'たな', 'まも', 'くへ', 'しつ',
  'ばぱは', 'びぴひ', 'ぶぷふ', 'べぺへ', 'ぼぽほ', 'そろ', 'すむ', 'とこ', 'のめ', 'らう', 'よま',
  // カタカナ
  'シツ', 'ソン', 'クケタ', 'ウワフ', 'アマ', 'コユロ', 'スヌ', 'チテ', 'ノメ', 'ルレ', 'セサ', 'ニコ',
  'ハヘ', 'ホオ', 'ミシ', 'ラヲ', 'リソ',
];

export function lookAlikes(unit: string): string[] {
  return GROUPS.filter((g) => g.includes(unit))
    .flatMap((g) => [...g])
    .filter((c) => c !== unit);
}
